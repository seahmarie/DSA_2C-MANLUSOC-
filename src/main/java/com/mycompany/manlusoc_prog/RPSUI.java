    private void btnPlayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPlayActionPerformed
        int p1 = cmbP1.getSelectedIndex();
        int p2 = cmbP2.getSelectedIndex();    
        
        if (p1 == 0 || p2 == 0){
            JOptionPane.showMessageDialog(
            this, "Please select Rock, Paper or Scissor");
        return;
        }
        else if (p1 == p2){
            lblResult.setText("Result : Draw!");
        }
        else if ((p1 == 1 && p2 == 3) || (p1 == 2 && p2 == 1) || (p1 == 3 && p2 == 2))
        { 
        p2buhay--;
        
        lblResult.setText("Player 1 Wins!");
        }
        else {
        p1buhay--;
        lblResult.setText("Player 2 Wins!");
        }
        
        lblP1Life.setText("Player 1 Lives :" + p1buhay);
        lblP2Life.setText("Player 2 Lives :" + p2buhay);
        
        round++;
        
        lblRound.setText("Round : " + round);
        
        if (p1buhay == 0){
        JOptionPane.showMessageDialog(
        this, "GAME OVER\nPlayer 2 Wins!");
        btnPlay.setEnabled(false);
        }
        
        else if (p2buhay == 0){
        JOptionPane.showMessageDialog(
        this, "GAME OVER\nPlayer 1 Wins!");
        btnPlay.setEnabled(false);
        }
    }//GEN-LAST:event_btnPlayActionPerformed

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
        p1buhay = 5;
        p2buhay = 5;
        round = 1;
        
        cmbP1.setSelectedIndex(0);
        cmbP2.setSelectedIndex(0);
        
        lblP1Life.setText("Player 1 Lives : " + p1buhay);
        lblP2Life.setText("Player 2 Lives : " + p2buhay);
        
        lblRound.setText("Round : " + round);
        
        lblResult.setText("Result : Waiting for game..");
        
        btnPlay.setEnabled(true);
    }//GEN-LAST:event_btnResetActionPerformed

